#!/usr/bin/env node
/**
 * Build the DSH client module from src/client into a single client.js.
 *
 * DSH's client loader evaluates `window.__ModuleLoader__.load({ factory })`
 * with its own `require`, so the bundle is wrapped in that envelope. The
 * factory body sets `globalThis.__qpReact` before the bundle runs; runtime.js
 * reads it at module-evaluation time.
 *
 * The esbuild CLI is used through its Node shim (stdio inherited) so the build
 * also works under the DSH Windows sandbox, where piped child stdout is denied.
 */
import { spawnSync } from 'node:child_process'
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const shim = join(root, 'node_modules', 'esbuild', 'bin', 'esbuild')
const temp = join(root, '.tmp-client-bundle.js')

const result = spawnSync(
  process.execPath,
  [
    shim,
    'src/client/main.js',
    '--bundle',
    '--format=iife',
    '--global-name=__qpModule',
    '--platform=browser',
    '--target=es2020',
    '--charset=utf8',
    '--legal-comments=none',
    `--outfile=${temp}`,
  ],
  { cwd: root, stdio: 'inherit' },
)
if (result.status !== 0) {
  rmSync(temp, { force: true })
  throw new Error(`esbuild exited ${String(result.status)}`)
}

const body = readFileSync(temp, 'utf8').replace(/\s+$/u, '')
rmSync(temp, { force: true })

const indented = body
  .split('\n')
  .map((line) => (line ? `      ${line}` : line))
  .join('\n')

const output = `/* Generated by scripts/build-client.mjs — edit src/client/ instead. */
window.__ModuleLoader__.load({
  id: 'dsh-quick-panel',
  factory(require) {
    globalThis.__qpReact = require('react')
    try {
${indented}
      return __qpModule.default
    } finally {
      delete globalThis.__qpReact
    }
  },
})
`

const previous = (() => {
  try {
    return readFileSync('client.js', 'utf8')
  } catch {
    return ''
  }
})()
writeFileSync('client.js', output)
console.log(`client.js ${output.length} bytes${output === previous ? ' (unchanged)' : ''}`)
